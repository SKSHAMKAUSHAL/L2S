import { test, describe, beforeEach, afterEach } from 'node:test';
import assert from 'node:assert';
import { aiRegistry } from '../src/ai/registry.js';
import { OllamaProvider } from '../src/ai/providers/ollama.js';
import { GroqProvider } from '../src/ai/providers/groq.js';
import { BaseLLMProvider, BaseSTTProvider, VALID_LLM_PROVIDERS, VALID_STT_PROVIDERS, maskApiKey, extractAndParseJSON } from '../src/ai/contracts.js';

describe('Prompt 3 — AI Provider Architecture & Contracts', () => {
  let originalFetch;

  beforeEach(() => {
    originalFetch = globalThis.fetch;
  });

  afterEach(() => {
    globalThis.fetch = originalFetch;
    // Restore default state
    aiRegistry.setActiveLLM('ollama');
    aiRegistry.setActiveSTT(process.env.GROQ_API_KEY ? 'groq_whisper' : 'local_whisper');
    aiRegistry.allowCloudFallback = false;
  });

  // ─── Contract & Allowlist Integrity ──────────────────────
  test('strictly permits ONLY ollama and groq as LLM providers', () => {
    assert.deepStrictEqual(VALID_LLM_PROVIDERS, ['ollama', 'groq']);
    assert.deepStrictEqual(VALID_STT_PROVIDERS, ['local_whisper', 'groq_whisper']);

    // Attempting to register an unapproved provider must throw
    assert.throws(() => {
      new BaseLLMProvider('openai', 'OpenAI', 'cloud', 'gpt-4o');
    }, /Invalid LLM provider ID/i);

    assert.throws(() => {
      new BaseLLMProvider('gemini', 'Gemini', 'cloud', 'gemini-1.5-pro');
    }, /Invalid LLM provider ID/i);

    assert.throws(() => {
      aiRegistry.setActiveLLM('claude');
    }, /Only 'ollama' and 'groq' are supported/i);
  });

  // ─── Secret Masking ──────────────────────────────────────
  test('masks API keys safely in all outputs', () => {
    assert.strictEqual(maskApiKey(''), '');
    assert.strictEqual(maskApiKey('short'), '********');
    assert.strictEqual(maskApiKey('gsk_1234567890abcdef'), 'gsk_...cdef');

    const groq = new GroqProvider({ apiKey: 'gsk_secretkey1234567890' });
    assert.strictEqual(groq.getMaskedKey(), 'gsk_...7890');
    assert.ok(!groq.getMaskedKey().includes('secretkey'));
  });

  // ─── Robust JSON Parser Utility ──────────────────────────
  test('extractAndParseJSON parses arrays, objects, and markdown code fences', () => {
    // Standard object
    assert.deepStrictEqual(extractAndParseJSON('{"title": "Test"}'), { title: 'Test' });

    // Standard array
    assert.deepStrictEqual(extractAndParseJSON('[{"id": 1}, {"id": 2}]'), [{ id: 1 }, { id: 2 }]);

    // Markdown fences around array
    const mdArray = '```json\n[\n  {"segment_id": "seg_1", "score": 85}\n]\n```';
    assert.deepStrictEqual(extractAndParseJSON(mdArray), [{ segment_id: 'seg_1', score: 85 }]);

    // Conversational prefix + markdown fence + object
    const conversational = 'Here is your structured JSON:\n```json\n{"success": true}\n```\nHope this helps!';
    assert.deepStrictEqual(extractAndParseJSON(conversational), { success: true });
  });

  // ─── Ollama Provider Adapter ─────────────────────────────
  test('OllamaProvider generateText succeeds with mocked daemon', async () => {
    globalThis.fetch = async (url, options) => {
      assert.ok(url.includes('/api/generate'));
      const body = JSON.parse(options.body);
      assert.strictEqual(body.model, 'llama3.2:3b');
      return {
        ok: true,
        json: async () => ({ response: 'This is an AI summary generated by Ollama.' }),
      };
    };

    const provider = new OllamaProvider({ model: 'llama3.2:3b' });
    const text = await provider.generateText({ prompt: 'Summarize video' });
    assert.strictEqual(text, 'This is an AI summary generated by Ollama.');
  });

  test('OllamaProvider generateStructuredJSON parses response into JSON', async () => {
    globalThis.fetch = async () => ({
      ok: true,
      json: async () => ({ response: '[{"segment_id": "seg_0", "overall_score": 90}]' }),
    });

    const provider = new OllamaProvider({ model: 'llama3.2:3b' });
    const structured = await provider.generateStructuredJSON({ prompt: 'Rank segments' });
    assert.ok(Array.isArray(structured));
    assert.strictEqual(structured[0].segment_id, 'seg_0');
    assert.strictEqual(structured[0].overall_score, 90);
  });

  test('OllamaProvider handles HTTP errors cleanly', async () => {
    globalThis.fetch = async () => ({
      ok: false,
      status: 500,
      statusText: 'Internal Server Error',
      text: async () => 'CUDA memory allocation error',
    });

    const provider = new OllamaProvider();
    await assert.rejects(
      async () => provider.generateText({ prompt: 'Fail test' }),
      /Ollama HTTP 500/i
    );
  });

  // ─── Groq Provider Adapter ───────────────────────────────
  test('GroqProvider rejects requests when API key is missing', async () => {
    const provider = new GroqProvider({ apiKey: '' });
    assert.strictEqual(provider.isConfigured(), false);
    await assert.rejects(
      async () => provider.generateText({ prompt: 'Test without key' }),
      /Groq API Key is missing/i
    );
  });

  test('GroqProvider generateText succeeds with mocked API', async () => {
    globalThis.fetch = async (url, options) => {
      assert.ok(url.includes('chat/completions'));
      assert.ok(options.headers.Authorization.includes('gsk_test_key'));
      return {
        ok: true,
        json: async () => ({
          choices: [{ message: { content: 'Groq ultra-fast response' } }],
        }),
      };
    };

    const provider = new GroqProvider({ apiKey: 'gsk_test_key', model: 'openai/gpt-oss-20b' });
    const text = await provider.generateText({ prompt: 'Hello Groq' });
    assert.strictEqual(text, 'Groq ultra-fast response');
  });

  test('GroqProvider handles 429 rate limit errors cleanly', async () => {
    globalThis.fetch = async () => ({
      ok: false,
      status: 429,
      text: async () => 'Rate limit exceeded: 6000 TPM limit reached',
    });

    const provider = new GroqProvider({ apiKey: 'gsk_test_key' });
    await assert.rejects(
      async () => provider.generateText({ prompt: 'Rate limit test' }),
      /rate limit exceeded/i
    );
  });

  test('GroqProvider generateStructuredJSON handles both array and object output', async () => {
    // Array test
    globalThis.fetch = async () => ({
      ok: true,
      json: async () => ({
        choices: [{ message: { content: '[{"id": "clip_1", "score": 95}]' } }],
      }),
    });

    const provider = new GroqProvider({ apiKey: 'gsk_test_key' });
    const arrayResult = await provider.generateStructuredJSON({ prompt: 'Rank clips' });
    assert.ok(Array.isArray(arrayResult));
    assert.strictEqual(arrayResult[0].id, 'clip_1');

    // Object test
    globalThis.fetch = async () => ({
      ok: true,
      json: async () => ({
        choices: [{ message: { content: '{"title": "Viral Hook", "caption": "Watch this!"}' } }],
      }),
    });

    const objResult = await provider.generateStructuredJSON({ prompt: 'Generate social' });
    assert.strictEqual(objResult.title, 'Viral Hook');
  });

  // ─── Provider Switching & Status Contract ────────────────
  test('aiRegistry.getStatusSummary contains warnings and zero raw secrets', async () => {
    globalThis.fetch = async (url) => {
      if (url.includes('models')) {
        return {
          ok: true,
          json: async () => ({ data: [{ id: 'openai/gpt-oss-20b' }, { id: 'qwen/qwen3.8-27b' }] }),
        };
      }
      return { ok: true, json: async () => ({ models: [{ name: 'llama3.2:3b' }] }) };
    };

    const summary = await aiRegistry.getStatusSummary();
    assert.ok(summary.activeLLM);
    assert.ok(summary.activeSTT);
    assert.ok(Array.isArray(summary.warnings));
    assert.ok(Array.isArray(summary.llmProviders));

    // Ensure raw API keys NEVER leak in summary
    const jsonStr = JSON.stringify(summary);
    assert.ok(!jsonStr.includes('gsk_test_key'));
  });

  // ─── Isolation & Fallback Prevention ─────────────────────
  test('strict isolation prevents silent cross-provider requests', async () => {
    let touchedOllama = false;
    let touchedGroq = false;

    globalThis.fetch = async (url) => {
      if (url.includes('11434')) touchedOllama = true;
      if (url.includes('groq.com')) touchedGroq = true;
      return {
        ok: true,
        json: async () => ({
          response: 'Ollama local response',
          choices: [{ message: { content: 'Groq cloud response' } }],
          models: [{ name: 'llama3.2:3b' }],
        }),
      };
    };

    // When Ollama is active, Groq must NEVER be called
    aiRegistry.setActiveLLM('ollama');
    const ollamaProvider = aiRegistry.getLLMProvider();
    await ollamaProvider.generateText({ prompt: 'Local only' });
    assert.strictEqual(touchedOllama, true);
    assert.strictEqual(touchedGroq, false);

    // Reset flags
    touchedOllama = false;
    touchedGroq = false;

    // When Groq is active, Ollama must NEVER be called
    aiRegistry.setActiveLLM('groq');
    aiRegistry.updateProviderKey('groq', 'gsk_isolation_test_key');
    const groqProvider = aiRegistry.getLLMProvider();
    await groqProvider.generateText({ prompt: 'Cloud only' });
    assert.strictEqual(touchedGroq, true);
    assert.strictEqual(touchedOllama, false);
  });
});
